"""Generate the immutable runtime projection from exact frozen input bytes."""
import argparse
from pathlib import Path
import pprint
import sys

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "tests/phase_b"))
from harness.contracts import CATALOG_SHA, PROTOCOL_SHA, load_contracts, projection
from harness.strict_json import Invalid

OUTPUT = ROOT / "src/lqcd_agent/control/_generated_protocol.py"


def render(protocol):
    header = '''"""Generated by scripts/generate_phase_b_protocol.py; do not edit."""
from types import MappingProxyType


def _freeze(value):
    if isinstance(value, dict):
        return MappingProxyType({key: _freeze(item) for key, item in value.items()})
    if isinstance(value, list):
        return tuple(_freeze(item) for item in value)
    return value


'''
    constants = f'PROTOCOL_SHA256 = "{PROTOCOL_SHA}"\nCATALOG_SHA256 = "{CATALOG_SHA}"\n'
    return (header + constants + "PROTOCOL = _freeze(" +
            pprint.pformat(projection(protocol), width=110, sort_dicts=False) + ")\n").encode()


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    try:
        protocol, _ = load_contracts()
        raw = render(protocol)
        if args.check:
            if not OUTPUT.is_file() or OUTPUT.read_bytes() != raw:
                print("ERROR: generated protocol is absent or stale", file=sys.stderr)
                return 1
        else:
            OUTPUT.parent.mkdir(parents=True, exist_ok=True)
            OUTPUT.write_bytes(raw)
    except (Invalid, OSError) as exc:
        print(f"ERROR: {exc}", file=sys.stderr)
        return 1
    print("Phase B generated protocol: byte-equal" if args.check else "Phase B protocol generated")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
